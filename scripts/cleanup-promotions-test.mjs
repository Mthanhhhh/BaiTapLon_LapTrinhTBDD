// Deletes only fixtures whose exact IDs AND generated test email prefix match a recorded test run.
import fs from 'node:fs';import assert from 'node:assert/strict';import {spawnSync} from 'node:child_process';
const file=process.argv[2];if(!file?.startsWith('.tools/promotions-test-'))throw Error('Pass an isolated fixture state file');
const s=JSON.parse(fs.readFileSync(file));assert.match(s.run,/^\d+$/);assert.equal(s.prefix,'promo.test.'+s.run);if(s.cleaned)throw Error('This run was already cleaned');
const ids=s.users.map(u=>u.id);assert.ok(ids.length>=2&&ids.every(Number.isSafeInteger));const users=ids.join(',');
const sql=q=>{const p=spawnSync('docker',['exec','-i','-e','MYSQL_PWD='+ (process.env.DB_PASSWORD||'root123'),'ecommerce-mysql','mysql','-uroot','-N','-B','--default-character-set=utf8mb4'],{input:q,encoding:'utf8'});if(p.status)throw Error(p.stderr);return p.stdout.trim();};
assert.equal(Number(sql(`SELECT COUNT(*) FROM auth_db.users WHERE id IN (${users}) AND email LIKE '${s.prefix}.%@example.invalid';`)),ids.length,'Fixture user prefix mismatch');
assert.equal(Number(sql(`SELECT COUNT(*) FROM product_db.shops WHERE id=${s.shopId} AND owner_user_id=${s.ownerId} AND name='CHỈ KIỂM THỬ ${s.run}';`)),1);
assert.equal(Number(sql(`SELECT COUNT(*) FROM product_db.products WHERE id=${s.productId} AND shop_id=${s.shopId} AND name='CHỈ KIỂM THỬ voucher ${s.run}';`)),1);
const campaigns=sql(`SELECT GROUP_CONCAT(id) FROM order_db.promo_campaigns WHERE created_by IN (${users});`);assert.match(campaigns,/^[\d,]+$/);
const orders=sql(`SELECT GROUP_CONCAT(id) FROM order_db.orders WHERE user_id IN (${users});`);assert.match(orders,/^[\d,]+$/);
sql(`USE order_db;
START TRANSACTION;
DELETE t FROM payment_db.payment_transactions t JOIN payment_db.payments p ON p.id=t.payment_id WHERE p.order_id IN (${orders});
DELETE r FROM payment_db.refunds r JOIN payment_db.payments p ON p.id=r.payment_id WHERE p.order_id IN (${orders});
DELETE FROM payment_db.payments WHERE order_id IN (${orders});
DELETE FROM order_db.promo_flash_reservations WHERE order_id IN (${orders});
DELETE FROM order_db.promo_redemptions WHERE order_id IN (${orders});
DELETE FROM order_db.promo_reservations WHERE order_id IN (${orders});
DELETE FROM order_db.orders WHERE id IN (${orders});
DELETE FROM order_db.carts WHERE user_id IN (${users});
DELETE FROM order_db.promo_wallet WHERE campaign_id IN (${campaigns});
DELETE FROM order_db.promo_reminders WHERE campaign_id IN (${campaigns});
DELETE FROM order_db.promo_flash_items WHERE campaign_id IN (${campaigns});
DELETE FROM order_db.promo_campaigns WHERE id IN (${campaigns});
DELETE FROM order_db.promo_shipping_policy WHERE shop_id=${s.shopId};
DELETE FROM product_db.inventory_movements WHERE sku_id=${s.skuId};
DELETE FROM product_db.stock_reservations WHERE sku_id=${s.skuId};
DELETE FROM product_db.product_skus WHERE product_id=${s.productId};
DELETE FROM product_db.products WHERE id=${s.productId} AND shop_id=${s.shopId};
DELETE FROM product_db.shops WHERE id=${s.shopId} AND owner_user_id=${s.ownerId};
DELETE FROM auth_db.app_notifications WHERE user_id IN (${users});
DELETE FROM auth_db.users WHERE id IN (${users}) AND email LIKE '${s.prefix}.%@example.invalid';
COMMIT;`);
s.cleaned=new Date().toISOString();fs.writeFileSync(file,JSON.stringify(s,null,2));
// Delete cached public catalog, not the user's real products/cart data.
const cache=spawnSync('docker',['exec','ecommerce-redis','redis-cli','DEL','promo:catalog'],{encoding:'utf8'});if(cache.status)throw Error(cache.stderr);
spawnSync('docker',['exec','ecommerce-redis','redis-cli','PUBLISH','eshop:promotions','fixture-cleanup'],{encoding:'utf8'});
console.log(JSON.stringify({cleaned:true,accounts:ids.length,fixtureShop:s.shopId,fixtureProduct:s.productId}));
