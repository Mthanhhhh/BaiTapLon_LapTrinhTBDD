export const locationKey = (value: string) => value.normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/đ/g,'d').replace(/Đ/g,'D').toLowerCase().replace(/thanh pho|tinh|tp[.]?/g,'').replace(/[^a-z0-9]/g,'');
export function resolveProvince(value?: string|null) {
 const key=locationKey(value||'');
 if(!key)return undefined;
 if(['hcm','tphcm','saigon','hochiminhcity','hcmc'].includes(key))return VIETNAM_PROVINCES.find(p=>p.name==='Hồ Chí Minh');
 if(key==='hanoi')return VIETNAM_PROVINCES[0];
 return VIETNAM_PROVINCES.find(p=>[p.name,...p.aliases].some(n=>locationKey(n)===key));
}
export const provinceLabel=(value?:string|null)=>resolveProvince(value)?.name||value?.trim()||'';
const radians=(n:number)=>n*Math.PI/180;
function distance(a:{lat:number;lon:number},b:{lat:number;lon:number}) {
 const x=Math.sin(radians(b.lat-a.lat)/2)**2+Math.cos(radians(a.lat))*Math.cos(radians(b.lat))*Math.sin(radians(b.lon-a.lon)/2)**2;
 return 6371*2*Math.atan2(Math.sqrt(x),Math.sqrt(1-x));
}
export function estimateDelivery(origin?:string|null,destination?:string|null) {
 const from=resolveProvince(origin),to=resolveProvince(destination);
 if(!from||!to)return null;
 const reference=distance(VIETNAM_PROVINCES[0],VIETNAM_PROVINCES.find(p=>p.name==='Hồ Chí Minh')!);
 const km=distance(from,to);
 // User-specified calibration: HCMC–Hanoi = 2–3 calendar days; minimum handling 1 day.
 const minDays=Math.max(1,Math.ceil(2*km/reference-1e-9));
 return {minDays,maxDays:minDays+1,approximateKm:Math.round(km),label:`${minDays}–${minDays+1} ngày`};
}
